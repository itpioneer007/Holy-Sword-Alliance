def load() -> list[dict]:
    recs = []
    for line in RAW.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        d, t, res, name = line.split(" ", 3)
        recs.append({"ts": f"{d} {t}", "res": res, "opp": name.strip()})
    recs.sort(key=lambda r: r["ts"])
    return recs


def main() -> None:
    dry = "--dry-run" in sys.argv
    recs = load()
    print(f"读入对局 {len(recs)} 场")

    # 按对手聚合 (时间升序)
    by_opp: dict[str, list[dict]] = {}
    for r in recs:
        by_opp.setdefault(r["opp"], []).append(r)

    first_loss, first_win_later_loss, pure_win = [], [], []
    for opp, rows in by_opp.items():
        first = rows[0]
        losses = [r for r in rows if r["res"] == "L"]
        if not losses:
            pure_win.append(opp)
        elif first["res"] == "L":
            first_loss.append(opp)
        else:
            first_win_later_loss.append(opp)

    ever_lost = sorted(by_opp.keys() - set(pure_win))
    first_loss = [o for o in first_loss] + [o for o in B_INCLUDE if o in by_opp]

    print(f"\n不同对手 {len(by_opp)} 人")
    print(f"  A 首次交锋即负 (入名单)      : {len(first_loss)}")
    print(f"  B 曾负但首战是胜利 (不入名单): {len(first_win_later_loss) - len(B_INCLUDE)}")
    print(f"  从未输过                     : {len(pure_win)}")
    print("\n--- B 类处理明细 ---")
    for o in sorted(first_win_later_loss):
        seq = " → ".join(f"{r['ts'][-5:]}{r['res']}" for r in by_opp[o])
        tag = "入名单(已核对方向)" if o in B_INCLUDE else "不入名单"
        print(f"  [{tag}] {o}  [{seq}]")

    cfg = Config()
    db = OpponentDB(cfg.db_path)
    before = db.stats()
    if dry:
        print(f"\n[dry-run] 未写库; 名单现状 {before}")
        return

    # 去重/纠字: 先与已有档案(含本次已写入的)做模糊归并, 再落 verdict='no'
    merged = []
    for o in sorted(first_loss):
        sim = db.find_similar(o)
        canonical = sim["name"] if sim and sim["name"] != o else o
        if canonical != o:
            merged.append((o, canonical))
        db.mark_no(canonical, reason="arena_record:first_attack_loss")
    after = db.stats()
    print(f"\n写库完成: 名单 {before.get('cannot_beat')} -> {after.get('cannot_beat')} "
          f"(+{after.get('cannot_beat', 0) - before.get('cannot_beat', 0)})")
    if merged:
        print("模糊归并(错字纠正):")
        for a, b in merged:
            print(f"   {a}  ->  {b}")


if __name__ == "__main__":
    main()
